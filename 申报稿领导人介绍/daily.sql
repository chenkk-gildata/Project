SELECT HASHCODE
     , B.GPDM
     , B.ZQJC
     , CONVERT(DATE, A.XXFBRQ) AS XXFBRQ
     , A.XXBT
     , A.FBSJ
FROM [10.101.0.212].JYPRIME.dbo.usrGSGGYWFWB A
     JOIN [10.101.0.212].JYPRIME.dbo.usrZQZB B 
     ON A.INBBM = B.INBBM 
     AND B.ZQSC IN (83, 90, 18) 
     AND B.ZQLB IN (1, 2, 41)
WHERE A.XXLB = 10 
AND A.NRLB IN (1, 25, 101)
AND A.XXLY IN (69, 70, 410007600) 
AND A.MTCC IN ('上海证券交易所','深圳证券交易所','北京证券交易所')
AND A.XXFBRQ > CONVERT(DATE,GETDATE()-30)
AND A.XXBT LIKE '%申报稿%'
AND NOT EXISTS (
     SELECT 1 FROM [10.101.0.212].JYPRIME.dbo.usrGSZYLDRJS X WHERE X.IGSDM=A.IGSDM
)